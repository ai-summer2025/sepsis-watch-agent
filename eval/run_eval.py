"""Evaluate sepsiswatch.

1. Score implementation: 6 observations scored by hand from the source definitions
   (eval/score_cases.json), designed to sit on threshold boundaries.
2. Extraction: 5 synthetic clinical notes with gold values and gold Sepsis-3 category
   (eval/notes_gold.json). Reports field accuracy and category accuracy.

  python eval/run_eval.py [--llm] [--check]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT.parent / "src"))

from sepsiswatch.assess import assess  # noqa: E402
from sepsiswatch.extract import extract_llm, extract_rules  # noqa: E402
from sepsiswatch.pipeline import observation_from_dict  # noqa: E402


def eval_scores():
    cases = json.loads((ROOT / "score_cases.json").read_text())
    failures = []
    for c in cases:
        a = assess(observation_from_dict({"id": c["id"], **c["observation"]}))
        by = {s.name: s for s in a.scores}
        for k, v in c["expected"].items():
            if k == "category":
                got = a.category
            elif k == "SOFA_components":
                for comp, pts in v.items():
                    if by["SOFA"].components[comp] != pts:
                        failures.append(f"{c['id']} SOFA.{comp}: expected {pts}, got {by['SOFA'].components[comp]}")
                continue
            else:
                got = by[k].total
            if got != v:
                failures.append(f"{c['id']} {k}: expected {v}, got {got}")
    return len(cases), failures


def _same(a, b) -> bool:
    if isinstance(b, bool) or isinstance(a, bool) or isinstance(b, str):
        return a == b
    try:
        return abs(float(a) - float(b)) <= 0.05
    except (TypeError, ValueError):
        return False


def eval_extraction(method, client=None):
    gold = json.loads((ROOT / "notes_gold.json").read_text())
    ok = n = cat_ok = 0
    errors = []
    for nid, g in sorted(gold.items()):
        text = (ROOT / "notes" / f"{nid}.txt").read_text()
        f = extract_rules(text) if method == "rules" else extract_llm(text, client)
        for k, v in g["fields"].items():
            n += 1
            if k in f and _same(f[k], v):
                ok += 1
            else:
                errors.append(f"{nid} {k}: expected {v}, got {f.get(k, '(missing)')}")
        for drug, dose in g.get("vasopressors", {}).items():
            n += 1
            if _same(f.get("vasopressors", {}).get(drug), dose):
                ok += 1
            else:
                errors.append(f"{nid} vasopressor {drug}: expected {dose}, got {f.get('vasopressors')}")
        cat = assess(observation_from_dict({"id": nid, **f})).category
        cat_ok += cat == g["category"]
        if cat != g["category"]:
            errors.append(f"{nid} category: expected {g['category']}, got {cat}")
    return {"field_accuracy": ok / n, "category_accuracy": cat_ok / len(gold), "n": len(gold), "errors": errors}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--llm", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    n, failures = eval_scores()
    ext = {"rules": eval_extraction("rules")}
    if args.llm:
        from sepsiswatch.llm import client_from_env
        ext["llm"] = eval_extraction("llm", client_from_env())
    out = ["# Evaluation results", "", "Generated by `python eval/run_eval.py`. All data is synthetic.", "",
           f"## Score implementation ({n} hand-scored observations)", ""]
    out += [f"- {x}" for x in failures] or ["All expected totals, SOFA components and categories match."]
    out += ["", f"## Extraction from notes ({ext['rules']['n']} notes)", "",
            "| Method | Field accuracy | Sepsis-3 category accuracy |", "|---|---|---|"]
    for m, r in ext.items():
        out.append(f"| {m} | {r['field_accuracy']:.2f} | {r['category_accuracy']:.2f} |")
    if "llm" not in ext:
        out.append("| llm | not run here: requires credentials. Run `python eval/run_eval.py --llm` | |")
    for m, r in ext.items():
        out += ["", f"### {m} errors", ""] + ([f"- {e}" for e in r["errors"]] or ["- none"])
    (ROOT / "RESULTS.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    if args.check:
        base = json.loads((ROOT / "baseline.json").read_text())
        if failures or ext["rules"]["field_accuracy"] < base["rules_field_accuracy"]:
            print("REGRESSION", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
