"""
Data models for the Sepsis Watch Agent.
"""
from dataclasses import dataclass, field
from typing import Optional, List, Dict
from enum import Enum


class SepsisStage(Enum):
    NO_SEPSIS = "NO_SEPSIS"
    WATCH = "WATCH"
    SUSPECT = "SUSPECT"
    SEPSIS = "SEPSIS"
    SEPTIC_SHOCK = "SEPTIC_SHOCK"


class AlertLevel(Enum):
    GREEN = "GREEN"
    YELLOW = "YELLOW"
    ORANGE = "ORANGE"
    RED = "RED"
    CRITICAL = "CRITICAL"


@dataclass
class Vitals:
    """Patient vital signs."""
    temperature_c: float          # Celsius
    heart_rate: int               # bpm
    respiratory_rate: int         # breaths/min
    systolic_bp: int              # mmHg
    diastolic_bp: int             # mmHg
    oxygen_saturation: float      # %
    gcs_score: int = 15           # Glasgow Coma Scale (3-15)
    urine_output_ml_hr: Optional[float] = None  # mL/hr

    @property
    def mean_arterial_pressure(self) -> float:
        return (self.systolic_bp + 2 * self.diastolic_bp) / 3


@dataclass
class LabValues:
    """Patient laboratory results."""
    wbc_count: Optional[float] = None         # x10^9/L (normal 4-11)
    bands_percent: Optional[float] = None      # % immature neutrophils
    lactate_mmol: Optional[float] = None       # mmol/L (normal <2)
    creatinine_mg_dl: Optional[float] = None   # mg/dL (normal 0.6-1.2)
    bilirubin_mg_dl: Optional[float] = None    # mg/dL (normal <1.2)
    platelet_count: Optional[float] = None     # x10^9/L (normal 150-400)
    paco2_mmhg: Optional[float] = None         # mmHg (normal 35-45)
    glucose_mg_dl: Optional[float] = None      # mg/dL (normal 70-140)


@dataclass
class ClinicalContext:
    """Patient clinical context."""
    patient_id: str
    age: int
    suspected_infection_source: str           # e.g. "pneumonia", "UTI", "unknown"
    altered_mentation: bool = False
    known_infection: bool = False
    immunocompromised: bool = False
    vasopressor_required: bool = False
    mechanical_ventilation: bool = False
    on_antibiotics: bool = False
    clinical_notes: str = ""


@dataclass
class SepsisScores:
    """Computed sepsis severity scores."""
    sirs_criteria_met: int = 0         # SIRS criteria count (0-4)
    qsofa_score: int = 0               # qSOFA (0-3)
    sofa_score: int = 0                # SOFA (0-24)
    news2_score: int = 0               # NEWS2 (0-20)
    stage: SepsisStage = SepsisStage.NO_SEPSIS
    alert_level: AlertLevel = AlertLevel.GREEN


@dataclass
class CareBundle:
    """Surviving Sepsis Campaign care bundle actions."""
    time_target: str                   # "1-hour", "3-hour", "6-hour"
    actions: List[str] = field(default_factory=list)
    completed: List[bool] = field(default_factory=list)

    @property
    def completion_rate(self) -> float:
        if not self.completed:
            return 0.0
        return sum(self.completed) / len(self.completed) * 100


@dataclass
class SepsisAlert:
    """Clinical alert generated by the agent."""
    patient_id: str
    alert_level: AlertLevel
    stage: SepsisStage
    scores: SepsisScores
    reasoning: str
    immediate_actions: List[str] = field(default_factory=list)
    care_bundles: List[CareBundle] = field(default_factory=list)
    evidence_citations: List[Dict] = field(default_factory=list)
    escalation_path: str = ""
    time_to_act_minutes: int = 60


@dataclass
class MonitoringCheckpoint:
    """Tracks patient response to interventions."""
    checkpoint_minutes: int
    vitals: Vitals
    labs: LabValues
    reassessment: str
    stage_change: Optional[SepsisStage] = None
    intervention_response: str = "pending"
